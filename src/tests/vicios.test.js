// Lote 175: os vícios (TC.vicios) — a necessidade, as faixas, cumprir, os dias do mundo e a biblioteca.
const V = require('../../tc/vicios.js');
let n = 0, bad = 0;
const ok = (c, m) => { n++; if (!c) { bad++; console.log('FALHOU: ' + m); } };
const j = JSON.stringify;
ok(j([0, 2.9, 3, 5.5, 6, 8.9, 9, 10].map(x => V.faixa(x).k)) === j(['tranquilo', 'tranquilo', 'inquieto', 'inquieto', 'fissura', 'fissura', 'desesperado', 'desesperado']), 'as faixas: 0–2 · 3–5 · 6–8 · 9–10');
ok(V.conta('+2 -1') === 1 && V.conta('−1,5') === -1.5 && V.conta('3') === 3 && V.conta('x') === null, 'a conta: "+2 -1", "−1,5"');
let r = V.mudar([], { t: 'nova', id: 'v1', n: ' Cigarro ', rit: 2, bx: 4, nec: 1, dia: 10, mp: 'm1' });
ok(r.mudou && r.a.n === 'Cigarro' && r.a.nec === 1 && r.a.dia === 10, 'novo vício');
r = V.mudar(r.lista, { t: 'nec', id: 'v1', d: 30 });
ok(r.a.nec === 10 && r.depois.k === 'desesperado', 'a necessidade não passa de 10');
r = V.mudar(r.lista, { t: 'cumprir', id: 'v1' });
ok(r.a.nec === 6 && r.antes.k === 'desesperado' && r.depois.k === 'fissura', 'cumprir sem dizer quanto: o "baixa ao cumprir" (4)');
r = V.mudar(r.lista, { t: 'cumprir', id: 'v1', d: 9 });
ok(r.a.nec === 0, 'cumprir não deixa abaixo de 0');
let a = V.avancar(r.lista, 13, 'm1');
ok(a.mudou && a.lista[0].nec === 6 && a.lista[0].dia === 13 && a.subiram.length === 1 && a.subiram[0].para.k === 'fissura', '3 dias × 2 = 6: subiu de faixa (o aviso)');
ok(!V.avancar(a.lista, 13, 'm1').mudou, 'o mesmo dia: nada muda');
a = V.avancar(a.lista, 11, 'm1');
ok(a.mudou && a.lista[0].nec === 6 && a.lista[0].dia === 11, 'o dia voltou (desfeito): só guarda o dia, sem baixar');
a = V.avancar(a.lista, 40, 'm2');
ok(a.lista[0].nec === 6 && a.lista[0].dia === 40 && a.lista[0].mp === 'm2', 'outro mapa: começa a contar dali, sem somar');
ok(!V.avancar(a.lista, null).mudou, 'sem o dia do mundo: nada');
const w = V.mudar(a.lista, { t: 'nova', id: 'v2', n: 'Jogo', oc: true }).lista;
ok(j(V.publica(w)) === j([{ id: 'v1', n: 'Cigarro', d: '', g: 'leve', nec: 6 }]), 'o jogador vê só os não secretos, com o grau, sem o ritmo');
ok(j(V.doJogador({ vic: [{ id: 'v1', n: 'C', nec: 99, rit: 5 }, { id: '!', n: 'x' }] })) === j([{ id: 'v1', n: 'C', d: '', g: 'leve', nec: 10 }]), 'a lista do jogador é lida com cuidado');
const mo = V.moldeDoVicio(w[0], 'vm1'), nv = V.doMolde(mo, 'v9', { dia: 5 });
ok(nv.nec === 0 && nv.m === 'vm1' && nv.rit === 2 && nv.dia === 5, 'da biblioteca: necessidade 0, ligado ao molde');
const ap = V.aplicarMolde([Object.assign({}, w[0], { m: 'vm1' })], Object.assign({}, mo, { rit: 3 }));
ok(ap.mudou && ap.lista[0].rit === 3 && ap.lista[0].nec === 6, 'o molde muda o ritmo das ligadas; a necessidade fica');
// lote 208: o grau (leve, médio, profundo) — de cada ficha, obrigatório, só uma marca
ok(V.norm([{ id: 'a', n: 'X' }])[0].g === 'leve' && V.norm([{ id: 'a', n: 'X', g: 'zzz' }])[0].g === 'leve', 'sem grau (ou grau estranho): leve');
let g = V.mudar([{ id: 'a', n: 'X', nec: 4, rit: 1 }], { t: 'editar', id: 'a', g: 'profundo' });
ok(g.mudou && g.a.g === 'profundo' && g.a.nec === 4 && g.a.rit === 1, 'editar o grau não mexe na necessidade nem no ritmo');
ok(V.avancar(g.lista, 0).lista[0].g === 'profundo' && V.mudar(g.lista, { t: 'cumprir', id: 'a' }).a.g === 'profundo', 'o grau fica ao cumprir e com os dias');
ok(j(V.publica(g.lista)[0]) === j({ id: 'a', n: 'X', d: '', g: 'profundo', nec: 4 }) && V.doJogador({ vic: V.publica(g.lista) })[0].g === 'profundo', 'o jogador vê o grau');
const mg = V.moldeDoVicio(g.a, 'vm2');
ok(!('g' in mg) && V.doMolde(mg, 'v7').g === 'leve' && V.doMolde(mg, 'v8', { g: 'medio' }).g === 'medio', 'o grau não vai para o molde; da biblioteca nasce leve');
ok(V.aplicarMolde([Object.assign({}, g.a, { m: 'vm2' })], Object.assign({}, mg, { rit: 2 })).lista[0].g === 'profundo', 'o molde não troca o grau de cada ficha');
ok(V.grau('medio').n === 'Médio' && V.grau(undefined).k === 'leve', 'os nomes dos graus');
console.log(bad ? `${n - bad} verificações passaram, ${bad} falharam` : `${n} verificações passaram`);
process.exit(bad ? 1 : 0);
